ARTICLE_TARGET.update({'population-plots': 'PLOT_GALLERY.md', 'growth-mortality': 'PLOT_GALLERY.md',
                       'model-comparison': 'PLOT_GALLERY.md'})

CJK = re.compile(r'[㐀-鿿]')


def blocks(text):
    """Split Markdown into typed blocks: (kind, lines)."""
    lines = text.rstrip('\n').split('\n')
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.startswith('```'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('```'):
                j += 1
            out.append(('code', lines[i:j + 1]))
            i = j + 1
            continue
        if re.match(r'<h[1-6]\b', line):
            out.append(('heading', [line]))
            i += 1
            continue
        if line.startswith('<div'):
            j = i
            while j < len(lines) and not lines[j].startswith('</div>'):
                j += 1
            out.append(('html', lines[i:j + 1]))
            i = j + 1
            continue
        if line.startswith('<'):
            out.append(('html', [line]))
            i += 1
            continue
        if re.match(r'#{1,6} ', line):
            out.append(('heading', [line]))
            i += 1
            continue
        if re.match(r'!\[[^\]]*\]\(', line) and line.rstrip().endswith(')'):
            out.append(('image', [line]))
            i += 1
            continue
        if line.startswith('|'):
            j = i
            while j < len(lines) and lines[j].startswith('|'):
                j += 1
            out.append(('table', lines[i:j]))
            i = j
            continue
        if re.match(r'\s*([-*]|\d+\.)\s', line):
            j = i
            while j < len(lines) and lines[j].strip():
                j += 1
            out.append(('list', lines[i:j]))
            i = j
            continue
        j = i
        while j < len(lines) and lines[j].strip() and not lines[j].startswith(('```', '|', '<', '#', '![')) \
                and not re.match(r'\s*([-*]|\d+\.)\s', lines[j]):
            j += 1
        out.append(('paragraph', lines[i:j]))
        i = j
    return out


def heading_parts(line):
    """Return (level, id, text) of a Markdown or HTML heading line."""
    m = re.match(r'<h([1-6])(?:\s+id="([^"]*)")?>(.*)</h[1-6]>', line.strip())
    if m:
        return int(m[1]), m[2], m[3].strip()
    m = re.match(r'(#{1,6}) (.*)', line)
    return len(m[1]), None, m[2].strip()


def code_lines(lines):
    """Split code and comments without interpreting hashes inside R strings."""
    quote = None
    raw_end = None
    out = []
    for line in lines:
        continuation = quote is not None or raw_end is not None
        i = 0
        comment_at = len(line)
        while i < len(line):
            char = line[i]
            if raw_end is not None:
                if line.startswith(raw_end, i):
                    i += len(raw_end)
                    raw_end = None
                    continue
            elif quote is not None:
                if char == "\\":
                    i += 2
                    continue
                if char == quote:
                    quote = None
            elif char == '#':
                comment_at = i
                break
            elif char in ('"', "'", '`'):
                quote = char
            elif char in 'rR' and (i == 0 or not (line[i - 1].isalnum() or line[i - 1] in '._')):
                raw = re.match(r"[rR]([\"'])(-*)([([{])", line[i:])
                if raw:
                    raw_end = {'(': ')', '[': ']', '{': '}'}[raw[3]] + raw[2] + raw[1]
                    i += len(raw[0])
                    continue
            i += 1
        code = line[:comment_at]
        comment = line[comment_at + 1:].strip() if comment_at < len(line) else None
        out.append((code, comment, bool(code.strip()) or continuation))
    return out


def code_signature(lines):
    """Executable lines, retaining hashes and blank lines inside strings."""
    if lines[0].startswith('```math'):
        body = tuple(line for line in lines[1:-1] if line.strip())
    else:
        body = tuple(code.rstrip() for code, _, executable in code_lines(lines[1:-1]) if executable)
    return lines[0].strip(), body


def check_alignment(slug, en, zh):
    if len(en) != len(zh):
        kinds = lambda b: ', '.join(k for k, _ in b)
        raise SystemExit(f'{slug}: English has {len(en)} blocks and Chinese {len(zh)}.\n'
                         f'  en: {kinds(en)}\n  zh: {kinds(zh)}')
    for n, ((ek, el), (zk, zl)) in enumerate(zip(en, zh), 1):
        if ek != zk:
            raise SystemExit(f'{slug}: block {n} is {ek} in English but {zk} in Chinese:\n'
                             f'  en: {el[0][:80]}\n  zh: {zl[0][:80]}')
        if ek == 'heading':
            e, z = heading_parts(el[0]), heading_parts(zl[0])
            if e[0] != z[0] or e[1] != z[1]:
                raise SystemExit(f'{slug}: heading {n} differs in level or id:\n  en: {el[0]}\n  zh: {zl[0]}')
        if ek == 'code' and code_signature(el) != code_signature(zl):
            raise SystemExit(f'{slug}: code block {n} differs between the languages (comments may differ, code may not):\n'
                             f'  en: {el[1][:80] if len(el) > 1 else el}\n  zh: {zl[1][:80] if len(zl) > 1 else zl}')
        if ek == 'table' and (len(el) != len(zl) or el[0].count('|') != zl[0].count('|')):
            raise SystemExit(f'{slug}: table {n} has different dimensions in the two languages.')
        if ek == 'list' and len(el) != len(zl):
            raise SystemExit(f'{slug}: list {n} has {len(el)} lines in English and {len(zl)} in Chinese.')


def map_links(text, slug):
    """Rewrite website links to their docs/ equivalents."""
    def one(m):
        label, url = m[1], m[2]
        target = url
        mm = re.match(r'(?:\.\./)?(?:articles/)?([a-z0-9-]+)\.html(#.*)?$', url)
        if mm and mm[1] in ARTICLE_TARGET:
            base = ARTICLE_TARGET[mm[1]]
            frag = mm[2]
            if frag:
                base = base.split('#')[0] + '#' + mm[1] + '-' + frag[1:] if not base.startswith('PLOT_GALLERY') else base + frag
            target = base
        elif re.match(r'\.\./reference/index\.html$', url):
            target = 'FUNCTION_REFERENCE.md'
        elif re.match(r'\.\./reference/([A-Za-z_.]+)\.html$', url):
            target = 'FUNCTION_REFERENCE.md#' + re.match(r'\.\./reference/([A-Za-z_.]+)\.html$', url)[1]
        elif url.startswith('../news/'):
            target = '../NEWS.md'
        elif url in ('../index.html', '../zh/index.html', 'index.html'):
            target = '../README.md'
        elif url.startswith('#'):
            target = '#' + slug + '-' + url[1:]
        elif '/assets/manual/' in url:
            target = url.split('/assets/manual/')[1]
        else:
            mm = re.match(re.escape(REPO) + r'/blob/main/docs/([^?#)]+)(?:\?raw=true)?', url)
            if mm:
                target = mm[1]
        return f'[{label}]({target})'
    text = re.sub(r'\[([^\]]*)\]\(([^)\s]+)\)', one, text)
    return text


def merge_table(el, zl):
    out = []
    for e, z in zip(el, zl):
        if set(e.strip()) <= set('|-: '):
            out.append(e)
            continue
        ec = [c.strip() for c in e.strip().strip('|').split('|')]
        zc = [c.strip() for c in z.strip().strip('|').split('|')]
        cells = [zc[k] if zc[k] == ec[k] or not ec[k] else (ec[k] if not zc[k] else f'{zc[k]} / {ec[k]}')
                 for k in range(len(ec))]
        out.append('| ' + ' | '.join(cells) + ' |')
    return out


def merge_code(el, zl):
    """Align executable lines first; translated comments cannot truncate code."""
    if code_signature(el) != code_signature(zl):
        raise ValueError('Cannot merge code blocks with different executable code.')
    if el[0].startswith('```math'):
        return list(el)

    def groups(lines):
        pending = []
        out = []
        for record in code_lines(lines[1:-1]):
            if record[2]:
                out.append((pending, record))
                pending = []
            else:
                pending.append(record)
        return out, pending

    def contains_comment(text, comment):
        return bool(text and comment) and (text == comment or
            text.startswith(comment + ' / ') or text.endswith(' / ' + comment) or
            ' / ' + comment + ' / ' in text)

    def combined_comment(en, zh):
        if not en or contains_comment(zh, en):
            return zh
        if not zh or contains_comment(en, zh):
            return en
        return zh + ' / ' + en

    def merge_notes(en, zh):
        english = [comment for _, comment, _ in en if comment]
        chinese = [comment for _, comment, _ in zh if comment]
        out = []
        if len(english) == len(chinese):
            translated = iter(chinese)
            for code, comment, _ in en:
                out.append(code + '# ' + combined_comment(comment, next(translated))
                           if comment else code)
        else:
            # Unequal comment counts do not establish line-by-line translation.
            # Keep each language's group intact, omitting only exact repeats or
            # an English comment already included in a bilingual Chinese line.
            seen = []
            for code, comment, _ in en:
                if not comment:
                    out.append(code)
                elif not any(contains_comment(text, comment) for text in chinese + seen):
                    out.append(code + '# ' + comment)
                    seen.append(comment)
            for code, comment, _ in zh:
                if comment and not any(contains_comment(text, comment) for text in seen):
                    out.append(code + '# ' + comment)
                    seen.append(comment)
        return out

    eg, etail = groups(el)
    zg, ztail = groups(zl)
    out = [el[0]]
    for (enotes, (ecode, ecomment, _)), (znotes, (_, zcomment, _)) in zip(eg, zg):
        out.extend(merge_notes(enotes, znotes))
        comment = combined_comment(ecomment, zcomment)
        separator = '' if not ecode or ecode[-1].isspace() else ' '
        out.append(ecode + (separator + '# ' + comment if comment else ''))
    out.extend(merge_notes(etail, ztail))
    out.append(el[-1])
    if code_signature(out) != code_signature(el):
        raise ValueError('Merged code differs from its source block.')
    return out


def render_pair(slug, level_shift=0):
    en_text = (WEB / 'en' / 'articles' / f'{slug}.md').read_text(encoding='utf-8')
    zh_text = (WEB / 'zh' / 'articles' / f'{slug}.md').read_text(encoding='utf-8')
    en, zh = blocks(map_links(en_text, slug)), blocks(map_links(zh_text, slug))
    check_alignment(slug, en, zh)
    out = []
    for (kind, el), (_, zl) in zip(en, zh):
        if kind == 'heading':
            level, hid, etext = heading_parts(el[0])
            _, _, ztext = heading_parts(zl[0])
            level = min(6, level + level_shift)
            if hid:
                out.append(f'<a id="{slug}-{hid}"></a>')
            # A shared step number is written once: "1. zh / en".
            num = re.match(r'(\d+\. )', etext)
            if num and ztext.startswith(num[1]):
                etext, ztext, prefix = etext[len(num[1]):], ztext[len(num[1]):], num[1]
            else:
                prefix = ''
            out.append('#' * level + ' ' + prefix + (ztext if ztext == etext else f'{ztext} / {etext}'))
        elif kind == 'paragraph':
            out.append('\n'.join(zl))
            out.append('\n'.join(el))
        elif kind == 'list':
            out.append('\n'.join(zl))
            out.append('\n'.join(el))
        elif kind == 'table':
            out.append('\n'.join(merge_table(el, zl)))
        elif kind == 'code':
            out.append('\n'.join(merge_code(el, zl)))
        elif kind == 'image':
            e = re.match(r'!\[([^\]]*)\]\((.*)\)', el[0])
            z = re.match(r'!\[([^\]]*)\]\((.*)\)', zl[0])
            alt = z[1] if z[1] == e[1] else f'{z[1]} / {e[1]}'
            out.append(f'![{alt}]({e[2]})')
        else:
            out.append('\n'.join(zl))
            out.append('\n'.join(el))
    return '\n\n'.join(out)


def title_of(slug, lang):
    text = (WEB / lang / 'articles' / f'{slug}.md').read_text(encoding='utf-8')
    m = re.search(r'^# (.+)$', text, re.M)
    return m[1].strip()


def section(slugs, number=None):
    parts = []
    for k, slug in enumerate(slugs):
        body = render_pair(slug, level_shift=1 if k == 0 else 2)
        if k == 0:
            # The article title becomes the section heading.
            zh, en = title_of(slug, 'zh'), title_of(slug, 'en')
            prefix = f'{number}. ' if number is not None else ''
            body = re.sub(r'^## .*$', f'## {prefix}{zh} / {en}', body, count=1, flags=re.M)
        else:
            zh, en = title_of(slug, 'zh'), title_of(slug, 'en')
            body = re.sub(r'^### .*$', f'<a id="{slug}"></a>\n### {zh} / {en}', body, count=1, flags=re.M)
        parts.append(body)
    return '\n\n'.join(parts)


def build_user_guide():
    version = re.search(r'^Version: (.+)$', (ROOT / 'DESCRIPTION').read_text(encoding='utf-8'), re.M)[1]
    toc = []
    bodies = []
    for n, (anchor, slugs) in enumerate(USER_GUIDE, 1):
        zh, en = title_of(slugs[0], 'zh'), title_of(slugs[0], 'en')
        toc.append(f'{n}. [{zh} / {en}](#{anchor})')
        bodies.append(f'<a id="{anchor}"></a>\n' + section(slugs, number=n))
    head = (f'# ALSCL 使用指南 / User guide\n\n{GENERATED}\n\n'
            f'**ALSCL {version} · 简体中文 / English**\n\n'
            '本指南按任务组织，每节先说明目的，再给出要运行的代码、应看到的结果和出错时的处理。'
            '网站提供单一语言的连续阅读：[English](https://fanzhang-lab-shou.github.io/ALSCL/) · '
            '[简体中文](https://fanzhang-lab-shou.github.io/ALSCL/zh/)。\n\n'
            'This guide is organized by task. Each section states its purpose, the code to run, what to expect '
            'and what to do when it fails. The website offers continuous reading in one language: '
            '[English](https://fanzhang-lab-shou.github.io/ALSCL/) · [简体中文](https://fanzhang-lab-shou.github.io/ALSCL/zh/).\n\n'
            '[首页 / Home](../README.md) · [函数参考 / Function reference](FUNCTION_REFERENCE.md) · '
            '[图谱 / Gallery](PLOT_GALLERY.md) · [评估工作流 / Assessment workflows](ASSESSMENT_WORKFLOWS.md) · '
            '[模型验证 / Model validation](MODEL_VALIDATION.md) · [应用案例 / Worked cases](CASES.md)\n\n'
            '## 目录 / Contents\n\n' + '\n'.join(toc) + '\n\n')
    write_output(DOCS / 'USER_GUIDE.md', head + '\n\n'.join(bodies) + '\n')


def build_documents():
    for name, (zh, en), slugs in DOCUMENTS:
        body = section(slugs)
        body = re.sub(r'^## ', '## ', body, count=1, flags=re.M)
        text = f'# {zh} / {en}\n\n{GENERATED}\n\n[使用指南 / User guide](USER_GUIDE.md) · [首页 / Home](../README.md)\n\n' + body + '\n'
        write_output(DOCS / name, text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail on stale outputs without writing files.')
    CHECK_ONLY = parser.parse_args().check
    build_user_guide()
    build_documents()
    if STALE:
        print('Stale generated manuals: ' + ', '.join(map(str, STALE)), file=sys.stderr)
        print('Run python3 scripts/build_manual.py to regenerate them.', file=sys.stderr)
        sys.exit(1)
    print(('Checked' if CHECK_ONLY else 'Built') + ' docs/USER_GUIDE.md and',
          ', '.join(name for name, _, _ in DOCUMENTS))
