    ('MODEL_VALIDATION.md', ('模型模拟与预测验证', 'Model simulation and prediction checks'), ['case-model-validation']),
    ('CASE_STUDIES.md', ('年度与季度案例', 'Annual and quarterly cases'), ['case-studies']),
