"""Build the bilingual manuals in docs/ from the website article pairs.

Run from the repository root: python3 scripts/build_manual.py
Then: python3 scripts/build_wiki.py
Use --check to compare the generated text without writing files.

Each tutorial is written twice, in website/content/en/articles/<slug>.md and
website/content/zh/articles/<slug>.md, with the same sequence of blocks
(headings, paragraphs, lists, tables, code, figures). This script checks that
alignment and interleaves the two files block by block into the bilingual
Markdown that README.md, the single-page book and the Wiki link to. Python
standard library only.
"""
from pathlib import Path
import argparse
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'website' / 'content'
DOCS = ROOT / 'docs'
CHECK_ONLY = False
STALE = []


def write_output(path, text):
    if CHECK_ONLY:
        if not path.is_file() or path.read_text(encoding='utf-8') != text:
            STALE.append(path.relative_to(ROOT))
    else:
        path.write_text(text, encoding='utf-8')


REPO = 'https://github.com/FanZhang-LAB-SHOU/ALSCL'
GENERATED = ('<!-- Generated by scripts/build_manual.py from website/content/{en,zh}/articles/. '
             'Edit the article pair, not this file. -->')

